#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t			i;
	unsigned char	*dest;

	i = 0;
	dest = s;
	while (i < n)
		dest[i++] = (unsigned char) c;
	return (s);
}
